// Ek ekran kontrolleri (flow.mjs sonrası çalışır)
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = (n) => page.screenshot({ path: `/tmp/shots/x-${n}.png` });
await page.goto('http://127.0.0.1:3000');
await page.getByRole('button', { name: 'Giriş yap' }).last().waitFor();
await page.getByLabel('Kullanıcı adı').fill('Sefa');
await page.getByLabel('Şifre').fill('yanlis');
await page.getByRole('button', { name: 'Giriş yap' }).last().click();
await page.getByText('Kullanıcı adı veya şifre hatalı.').waitFor();
await page.getByLabel('Şifre').fill('sifre123');
await page.getByRole('button', { name: 'Giriş yap' }).last().click();
await page.getByText('Yeni maç').waitFor();
for (const nm of ['Okan', 'Caner', 'Burak', 'Tolga']) await page.getByRole('button', { name: nm, exact: true }).click();
await page.getByRole('button', { name: 'Elle diz' }).click();
await shot('elle-diz');
const rows = ['Mavi forvet', 'Mavi kaleci', 'Kırmızı forvet', 'Kırmızı kaleci'];
const pick = ['Tolga', 'Okan', 'Caner', 'Burak'];
for (let i = 0; i < 4; i++) await page.getByText(rows[i], { exact: true }).locator('..').getByRole('button', { name: pick[i] }).click();
await page.getByRole('button', { name: 'Kadroyu kullan' }).click();
await page.getByRole('button', { name: 'Oranları çıkar, bahsi aç' }).click();
await page.getByText('Bahis açık').waitFor({ timeout: 15000 });
await wait(400);
await shot('bulten-ust');
await page.getByText('Oranlar nasıl çıktı?').click();
await wait(500);
await shot('oran-aciklama');
await page.mouse.click(200, 60);
await wait(500);
await page.locator('#main').evaluate((el) => el.scrollTo(0, 900));
await wait(300);
await shot('bulten-goller');
await page.locator('#main').evaluate((el) => el.scrollTo(0, 99999));
await wait(300);
await shot('bulten-oyuncular');
await page.locator('nav').getByRole('button', { name: 'İstatistik' }).click();
await page.getByRole('button', { name: /Tolga/ }).first().click();
await wait(500);
await shot('oyuncu-detay');
await page.mouse.click(200, 60);
await wait(400);
await page.getByRole('button', { name: 'Enler' }).click();
await shot('enler');
await page.getByRole('button', { name: 'İkililer' }).click();
await shot('ikililer');
await page.getByRole('button', { name: 'Maçlar' }).click();
await page.locator('#main button').filter({ hasText: '5-2' }).first().click();
await wait(600);
await shot('mac-detay');
console.log(errors.length ? errors.join('\n') : 'HATA YOK');
await browser.close();
